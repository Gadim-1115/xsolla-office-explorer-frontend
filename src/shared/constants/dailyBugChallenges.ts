export function getTodayDateKey(now: Date = new Date()): string {
  const year = now.getFullYear()
  const month = String(now.getMonth() + 1).padStart(2, '0')
  const day = String(now.getDate()).padStart(2, '0')
  return `${year}-${month}-${day}`
}

export function getYesterdayDateKey(now: Date = new Date()): string {
  const copy = new Date(now.getFullYear(), now.getMonth(), now.getDate() - 1)
  return getTodayDateKey(copy)
}

export function getDailyBugChallenge(dateKey: string = getTodayDateKey()): DailyBugChallenge {
  let hash = 0
  for (let i = 0; i < dateKey.length; i++) {
    hash = (hash * 31 + dateKey.charCodeAt(i)) >>> 0
  }
  const index = hash % DAILY_BUG_CHALLENGES.length
  return DAILY_BUG_CHALLENGES[index]
}
